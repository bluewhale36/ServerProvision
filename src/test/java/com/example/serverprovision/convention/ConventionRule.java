package com.example.serverprovision.convention;

/**
 * 기계로 검사하는 코딩 규약 목록. 규칙마다 무엇을 막는지와 어떻게 고치는지를 한 곳에 둔다.
 * 실패 메시지와 기준선 대조가 이 문장을 함께 쓴다.
 */
enum ConventionRule {

	A1(Engine.ARCHITECTURE, "컨트롤러에 @Transactional 을 두지 않는다.",
			"트랜잭션은 Service 메서드에 둔다(CLAUDE.md 레이어 경계)."),
	A2(Engine.ARCHITECTURE, "컨트롤러는 Repository 를 직접 쓰지 않는다.",
			"Service 를 거쳐 조회 · 저장한다(CLAUDE.md 레이어 경계)."),
	A3(Engine.ARCHITECTURE, "컨트롤러는 엔티티를 직접 다루지 않는다.",
			"Service 가 *Response 로 바꿔 넘긴다. 뷰 모델에 엔티티를 넣지 않는다(CLAUDE.md 레이어 경계)."),
	A4(Engine.ARCHITECTURE, "dto.request 클래스는 Request 로, dto.response 클래스는 Response 로 끝나고 DTO 접미사를 쓰지 않는다.",
			"이름을 바꾸거나, 요청 · 응답이 아닌 도우미는 dto 밖으로 옮긴다(CLAUDE.md 네이밍)."),
	A5(Engine.ARCHITECTURE, "management 서비스는 TypedNameVerifier · MarkableScanner · ObjectProvider 를 주입받지 않는다.",
			"이름 확인은 컨트롤러가 하고, 스캐너는 reconciliation 쪽에서 쓴다. 주입하면 생성자 순환이 다시 생긴다(CLAUDE.md 핵심 설계 패턴)."),
	A6(Engine.ARCHITECTURE, "엔티티와 DTO 의 mac · ip 값은 String 이 아니다.",
			"MacAddress · IpAddress 같은 값 객체를 쓴다(CLAUDE.md Primitive Obsession 금지)."),
	A7(Engine.ARCHITECTURE, "패키지 이름은 소문자다.",
			"패키지 이름을 소문자로 바꾼다(CLAUDE.md 네이밍)."),

	S1(Engine.SOURCE, "컨트롤러 메서드 안에 try 문을 두지 않는다.",
			"예외를 HTTP 응답으로 바꾸는 일은 @ControllerAdvice · resolver 로 올린다(CLAUDE.md 조건분기 legacy 확장 금지)."),
	S2(Engine.SOURCE, "메서드 본문은 100 줄을 넘지 않는다.",
			"검증 · 변환 · 입출력 · 응답 조립을 작은 메서드로 나눈다(CLAUDE.md 중복 · 가독성 금지)."),
	S3(Engine.SOURCE, "제어 구조를 5 단계 이상 겹치지 않는다.",
			"이른 반환이나 작은 메서드로 단계를 줄인다(CLAUDE.md 중복 · 가독성 금지)."),
	S4(Engine.SOURCE, "주석에 AI 작성 표지를 두지 않는다.",
			"'// Claude', '@author Claude', 'Generated by' 같은 표지를 지운다. AI 참여는 커밋 메시지에 남긴다(CLAUDE.md 코딩 스타일)."),

	J1(Engine.SOURCE, "멤버 Javadoc 본문은 4 줄을 넘지 않는다.",
			"무엇과 왜만 남긴다. 긴 설계 배경은 타입 Javadoc 한 곳에 둔다(.claude/domain-conventions/javadoc.md)."),
	J2(Engine.SOURCE, "타입 Javadoc 본문은 8 줄을 넘지 않는다.",
			"지금의 역할과 이유만 남기고, 경위는 커밋 · plan 에 둔다(.claude/domain-conventions/javadoc.md)."),
	J3(Engine.SOURCE, "Javadoc 첫 문장을 단계 코드로 시작하지 않는다.",
			"첫 문장은 이 코드가 지금 하는 일을 말한다. 단계 이력은 커밋 · plan 에 둔다(.claude/domain-conventions/javadoc.md)."),
	J4(Engine.SOURCE, "Javadoc 에 화살표를 쓰지 않는다.",
			"'A 하면 B 가 된다' 처럼 문장으로 쓴다. 코드 예시는 {@code} 안에 둔다(.claude/domain-conventions/javadoc.md)."),
	J5(Engine.SOURCE, "Javadoc 에 괄호 안 괄호를 쓰지 않는다.",
			"괄호 속 설명을 문장 하나로 꺼낸다(.claude/domain-conventions/javadoc.md).");

	/** 규칙을 판정하는 검사. 기준선 대조는 검사마다 자기 규칙의 줄만 본다. */
	enum Engine { ARCHITECTURE, SOURCE }

	private final Engine engine;
	private final String title;
	private final String fix;

	ConventionRule(Engine engine, String title, String fix) {
		this.engine = engine;
		this.title = title;
		this.fix = fix;
	}

	Engine engine() {
		return engine;
	}

	String title() {
		return title;
	}

	String fix() {
		return fix;
	}
}
