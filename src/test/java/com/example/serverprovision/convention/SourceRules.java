package com.example.serverprovision.convention;

import com.github.javaparser.ast.Node;
import com.github.javaparser.ast.body.CallableDeclaration;
import com.github.javaparser.ast.body.TypeDeclaration;
import com.github.javaparser.ast.comments.Comment;
import com.github.javaparser.ast.expr.LambdaExpr;
import com.github.javaparser.ast.expr.ObjectCreationExpr;
import com.github.javaparser.ast.expr.SwitchExpr;
import com.github.javaparser.ast.stmt.BlockStmt;
import com.github.javaparser.ast.stmt.DoStmt;
import com.github.javaparser.ast.stmt.ForEachStmt;
import com.github.javaparser.ast.stmt.ForStmt;
import com.github.javaparser.ast.stmt.IfStmt;
import com.github.javaparser.ast.stmt.SwitchStmt;
import com.github.javaparser.ast.stmt.SynchronizedStmt;
import com.github.javaparser.ast.stmt.TryStmt;
import com.github.javaparser.ast.stmt.WhileStmt;

import java.util.List;
import java.util.Optional;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * 소스 구문 트리로 판정하는 규칙(S1 ~ S4). 메서드 본문 줄 수와 중첩 깊이는 구문 트리로 세므로
 * record 선언이나 익명 클래스를 메서드로 잘못 세지 않는다.
 */
final class SourceRules {

	static final int MAX_BODY_LINES = 100;
	static final int MAX_NESTING = 4;
	private static final Pattern AI_MARKER = Pattern.compile("(?i)^\\s*(claude\\b|generated by\\b)|@author\\s+claude");

	private SourceRules() {
	}

	static Stream<ConventionViolation> check(SourceFile file) {
		Stream<ConventionViolation> callables = namedCallables(file).flatMap(callable -> Stream.of(
				tryInController(file, callable),
				longBody(file, callable),
				deepNesting(file, callable)).flatMap(Optional::stream));
		return Stream.concat(callables, aiMarkers(file));
	}

	/** 이름 있는 타입에 바로 선언된 메서드 · 생성자만 센다. 익명 클래스의 메서드는 바깥 메서드에 속한다. */
	private static Stream<CallableDeclaration<?>> namedCallables(SourceFile file) {
		return file.unit().findAll(CallableDeclaration.class).stream()
				.<CallableDeclaration<?>>map(c -> c)
				.filter(c -> c.getParentNode().filter(TypeDeclaration.class::isInstance).isPresent());
	}

	private static Optional<BlockStmt> body(CallableDeclaration<?> callable) {
		return callable.findFirst(BlockStmt.class, block -> block.getParentNode().filter(callable::equals).isPresent());
	}

	private static Optional<ConventionViolation> tryInController(SourceFile file, CallableDeclaration<?> callable) {
		boolean hasTry = file.isController() && body(callable).flatMap(b -> b.findFirst(TryStmt.class)).isPresent();
		return hasTry ? Optional.of(new ConventionViolation(ConventionRule.S1, file.path(), file.callable(callable))) : Optional.empty();
	}

	private static Optional<ConventionViolation> longBody(SourceFile file, CallableDeclaration<?> callable) {
		return body(callable)
				.filter(b -> b.getBegin().isPresent() && b.getEnd().isPresent())
				.map(b -> b.getEnd().get().line - b.getBegin().get().line - 1)
				.filter(lines -> lines > MAX_BODY_LINES)
				.map(lines -> new ConventionViolation(ConventionRule.S2, file.path(), file.callable(callable), lines + " 줄"));
	}

	private static Optional<ConventionViolation> deepNesting(SourceFile file, CallableDeclaration<?> callable) {
		return body(callable)
				.map(SourceRules::depth)
				.filter(depth -> depth > MAX_NESTING)
				.map(depth -> new ConventionViolation(ConventionRule.S3, file.path(), file.callable(callable), depth + " 단계"));
	}

	/** 노드 아래에서 제어 구조가 가장 깊게 겹친 단계 수. else if 는 한 단계로 본다. */
	static int depth(Node node) {
		int max = 0;
		for (Node child : node.getChildNodes()) {
			if (child instanceof TypeDeclaration<?> || isAnonymousClass(child)) {
				continue;
			}
			max = Math.max(max, depth(child) + (isLevel(child, node) ? 1 : 0));
		}
		return max;
	}

	private static boolean isAnonymousClass(Node node) {
		return node instanceof ObjectCreationExpr creation && creation.getAnonymousClassBody().isPresent();
	}

	private static boolean isLevel(Node child, Node parent) {
		if (child instanceof IfStmt) {
			return !(parent instanceof IfStmt parentIf && parentIf.getElseStmt().filter(child::equals).isPresent());
		}
		if (child instanceof LambdaExpr lambda) {
			return lambda.getBody().isBlockStmt();
		}
		return LEVEL_TYPES.stream().anyMatch(type -> type.isInstance(child));
	}

	private static final List<Class<? extends Node>> LEVEL_TYPES = List.of(
			ForStmt.class, ForEachStmt.class, WhileStmt.class, DoStmt.class,
			SwitchStmt.class, SwitchExpr.class, TryStmt.class, SynchronizedStmt.class);

	private static Stream<ConventionViolation> aiMarkers(SourceFile file) {
		return file.unit().getAllComments().stream()
				.filter(comment -> AI_MARKER.matcher(comment.getContent()).find())
				.map(comment -> new ConventionViolation(ConventionRule.S4, file.path(), markerOwner(file, comment)));
	}

	private static String markerOwner(SourceFile file, Comment comment) {
		return comment.getCommentedNode().map(file::typeOf).orElseGet(() -> file.typeOf(comment));
	}
}
